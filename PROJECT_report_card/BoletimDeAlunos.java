    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        try{
        
            File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/alunos.txt");
            
            if(arquivo.createNewFile()){
                System.out.printf("O arquivo %s foi criado com Sucosso", arquivo.getName());
            }else{
                System.out.printf("O arquivo %s já existe", arquivo.getName());
            }
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao criar o arquivo. Erro: "+ e.getMessage());
        }
        
        String caminho = "/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/alunos.txt";
        
        Double nota1 = Double.parseDouble(txtNota1.getText().trim());
        Double nota2 = Double.parseDouble(txtNota2.getText().trim());
        
        Double mediaNota = (nota1 + nota2) / 2;
        
        try(PrintWriter escritor = new PrintWriter(new FileWriter(caminho, true))){
            if(mediaNota >= 7 && mediaNota <= 10){
                
                escritor.printf("\n Aluno %s | Nota 1: %.2f | Nota 2: %.2f | Média: %.2f | Situação: Aprovado \n", txtNome.getText().trim(),nota1 ,nota2 ,mediaNota);
                JOptionPane.showMessageDialog(this, "Nota Cadastrada com sucesso!");

            }else if(mediaNota >= 5 && mediaNota <= 6.9){

                escritor.printf("\n Aluno %s | Nota 1: %.2f | Nota 2: %.2f | Média: %.2f | Situação: Recuperação \n", txtNome.getText().trim(),nota1 ,nota2 ,mediaNota);
                JOptionPane.showMessageDialog(this, "Nota Cadastrada com sucesso!");

            }else if(mediaNota >= 0 && mediaNota <= 4.9){

                escritor.printf("\n Aluno %s | Nota 1: %.2f | Nota 2: %.2f | Média: %.2f | Situação: Reprovado \n", txtNome.getText().trim(),nota1 ,nota2 ,mediaNota);
                JOptionPane.showMessageDialog(this, "Nota Cadastrada com sucesso!");

            }else{
                
            }
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao escrever no arquivo. Erro: "+ e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        
        File arquivo = new File("/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/alunos.txt");
        
        if(!arquivo.exists()){
            JOptionPane.showMessageDialog(this, "Nenhum dado salvo!");
            return;
        }
        
        DefaultTableModel modelo = new DefaultTableModel(new Object[] {"Nome","Nota 1", "Nota 2", "Média", "Situação"}, 0);
        
        try(Scanner leitor = new Scanner(arquivo)){
            
            while(leitor.hasNextLine()){
                String linha = leitor.nextLine();
                
                if(linha.isEmpty()) continue;
                
                String[] campos = linha.split("\\|");
                
                if(campos.length == 5){
                    modelo.addRow(new Object[]{
                        campos[0].replace("Aluno", "").trim(),
                        campos[1].replace("Nota 1:", "").trim(),
                        campos[2].replace("Nota 2:", "").trim(),
                        campos[3].replace("Média", "").trim(),
                        campos[4].replace("Situação:", "").trim(),
                    });
                }
            }
            
            tblResultados.setModel(modelo);
            
        }catch(FileNotFoundException e){
            JOptionPane.showMessageDialog(this, "Erro na Leitura do arquivo. Erro: "+ e.getMessage());
        }
    }//GEN-LAST:event_btnListarActionPerformed


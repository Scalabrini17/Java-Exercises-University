    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        String nomeArquivo = txtNomeArquivo.getText().trim().toLowerCase();
        
        String txtNotas = txtarNotas.getText();
        
        if(nomeArquivo.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Digite o nome do arquivo!", "Aviso!", JOptionPane.WARNING_MESSAGE);
            return;
            
        }
        
        if(txtNotas.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Digite uma nota no campo de texto para poder salvar o arquivo!");
            return;
            
        }
        
        File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/" + nomeArquivo + ".txt");
            
        if (arquivo.exists()){  
                
            int resposta = JOptionPane.showConfirmDialog(this, "O arquivo " + nomeArquivo + " já existe! Deseja substituir?", "Confirmar Substituição", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
               
            if (resposta != JOptionPane.YES_OPTION){
                
                return;
                    
            }
                
        }
        
        try(FileWriter escritor = new FileWriter(arquivo) ) {
            
            escritor.write(txtarNotas.getText());
            
            JOptionPane.showMessageDialog(this, "Arquivo salvo com sucesso!");
            
        }catch(IOException e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar o arquivo! Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNovoActionPerformed
        
        String nomeArquivo = txtNomeArquivo.getText().trim().toLowerCase();
        
        String txtNotas = txtarNotas.getText();
        
        if(nomeArquivo.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Digite o nome do arquivo!", "Aviso!", JOptionPane.WARNING_MESSAGE);
            return;
            
        }
        
        File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/" + nomeArquivo + ".txt");
            
        int resposta = JOptionPane.showConfirmDialog(this, "Há conteúdo não salvo", "Deseja Salvar antes de criar um novo?", JOptionPane.YES_NO_CANCEL_OPTION, JOptionPane.WARNING_MESSAGE);
              
        if (resposta == JOptionPane.CLOSED_OPTION || resposta == JOptionPane.CANCEL_OPTION){
                
            return;
                
        }
        
        if(resposta == JOptionPane.YES_OPTION) {
                
            if (arquivo.exists()){  
                
                int respostaSeExistir = JOptionPane.showConfirmDialog(this, "O arquivo " + nomeArquivo + " já existe! Deseja substituir?", "Confirmar Substituição", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

                if (respostaSeExistir != JOptionPane.YES_OPTION){

                    return;

                }

            }
            
            try(FileWriter escritor = new FileWriter(arquivo) ) {
            
                escritor.write(txtarNotas.getText());

                JOptionPane.showMessageDialog(this, "Arquivo salvo com sucesso!");

            }catch(IOException e) {
                JOptionPane.showMessageDialog(this, "Erro ao salvar o arquivo! Erro: " + e.getMessage());
                return;
            }
                
        }
            
        txtNomeArquivo.setText("");
               
        txtarNotas.setText("");
            
    
        
    }//GEN-LAST:event_btnNovoActionPerformed

    private void btnAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirActionPerformed
        
        String nomeArquivo = txtNomeArquivo.getText().trim().toLowerCase();
        
        File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/" + nomeArquivo + ".txt");
        
        if(nomeArquivo.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Digite o nome do arquivo para abrir!");
            return;
            
        }
        
        if(!arquivo.isFile()){
            
            JOptionPane.showMessageDialog(this, "Arquivo não encontrado!");
            return;
            
        }
        
        if(arquivo.isFile()){
        
            try(BufferedReader leitor = new BufferedReader(new FileReader(arquivo))){
                
                StringBuilder conteudo = new StringBuilder();
                
                String linha;
                
                while((linha = leitor.readLine()) != null){
                    conteudo.append(linha).append("\n");
                }
                
                txtarNotas.setText(conteudo.toString());
                
            }catch(IOException e){
                JOptionPane.showMessageDialog(this, "Erro ao abrir o arquivo " + nomeArquivo + " Erro: " + e.getMessage());
            }
            
        }
        
    }//GEN-LAST:event_btnAbrirActionPerformed


    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        
        Path caminho = Paths.get("/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/contatos.txt");
        
        try{
            
            String conteudo = Files.readString(caminho);
            
            txtarLista.setText(conteudo);
            
        }catch(IOException e){
            
            txtarLista.setText("");
            JOptionPane.showMessageDialog(this, "Não foi possivel encontrar o arquivo! Erro: " + e.getMessage());
            
        }
        
    }//GEN-LAST:event_btnListarActionPerformed


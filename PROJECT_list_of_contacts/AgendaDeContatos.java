    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        try{
            
            File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/contatos.txt");
            
            if(arquivo.createNewFile()){
                
                System.out.println("Arquivo criado com sucesso!");
                JOptionPane.showMessageDialog(this, "Arquivo criado com sucesso!");
                
            }else{
                
                System.out.println("Arquivo já criado");
                
            }
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao criar o arquivo. Erro: " + e.getMessage());
        }
        
        String caminho = "/home/scalabrini/NetBeansProjects/Atividade22_10/src/main/java/com/mycompany/atividade22_10/contatos.txt";
        
        try(PrintWriter escritor = new PrintWriter(new FileWriter(caminho, true))){
        
            if(txtNome.getText().trim().isEmpty() || txtTelefone.getText().trim().isEmpty() || txtEmail.getText().trim().isEmpty()){
                
                JOptionPane.showMessageDialog(this, "Preencha todos os campos para o cadastro do contato!");
                
            }else if(!txtEmail.getText().contains("@")){
            
                JOptionPane.showMessageDialog(this, "E-mail inválido, falta o caracter (@)");
                
            }else {
            
                escritor.printf("\n Nome: %s; Telefone: %s; E-mail: %s \n", txtNome.getText(), txtTelefone.getText(), txtEmail.getText());
                JOptionPane.showMessageDialog(this, "Contato cadastrado com sucesso!");
                
            }
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao inserir o contato! Erro: " + e.getMessage());
        }
            
    }//GEN-LAST:event_btnSalvarActionPerformed


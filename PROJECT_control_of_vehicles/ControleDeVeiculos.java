    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        try{
        
            File arquivo = new File ("/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/veiculos.txt");
            
            if(arquivo.createNewFile()){
                
                JOptionPane.showMessageDialog(this, "Arquivo criado com sucesso!");
                
            }else{
                
                JOptionPane.showMessageDialog(this, "O arquivo já foi criado!");
                
            }
            
        }catch(IOException e) {
            JOptionPane.showMessageDialog(this, "Erro ao criar o arquivo. Erro: "+ e.getMessage());
        }
        
        String caminho = "/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/veiculos.txt";
        
        int ano = Integer.parseInt(txtAno.getText().trim());
        
        try(PrintWriter escritor = new PrintWriter(new FileWriter(caminho, true))){
            
            if(rdbtnCarro.isSelected()){
                
                escritor.printf("\n O Carro tem Placa: %s | Modelo: %s | Ano: %d \n", txtPlaca.getText().trim(), txtModelo.getText().trim(), ano);
            
            }else if(rdbtnMoto.isSelected()){
                
                escritor.printf("\n A Moto tem Placa: %s | Modelo: %s | Ano: %d \n", txtPlaca.getText().trim(), txtModelo.getText().trim(), ano);
                
            }
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao escrever no arquivo. Erro: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        String placa = txtPlaca.getText().trim();
        
        File arquivo = new File("/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/veiculos.txt");
        
        String caminho = "/home/scalabrini/NetBeansProjects/Atividade20_10/src/main/java/com/mycompany/atividade20_10/veiculos.txt";
        
        if(placa.equals("")){
            JOptionPane.showMessageDialog(this, "Digite as informações da placa!");
        }
            
        if(arquivo.isFile() && arquivo.canRead()){
                
        }else{
            JOptionPane.showMessageDialog(this, "Nenhum Veículo cadastrado");
        }
        
        try(BufferedReader leitor = new BufferedReader(new FileReader(caminho))){
        
            String linha;
            
            txtarBusca.setText("");
            
            boolean encontrou = false;
            
           while((linha = leitor.readLine()) != null){
               if(linha.toLowerCase().contains(placa.toLowerCase())){ // Aprendi que o contains procura a placa em qualquer parte da linha ISSO É MUITO INTERESSANTE
                   
                   txtarBusca.append(linha + "\n");
                   encontrou = true;
               }
            }
            if(!encontrou){
                txtarBusca.setText("Nenhum veículo encontrado");
            }
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Erro ao procurar o arquivo. Erro:" + e.getMessage());
        }
        
    }//GEN-LAST:event_btnBuscarActionPerformed

